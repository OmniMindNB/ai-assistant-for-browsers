const esc = (value) =>
  String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');

const text = (x, y, value, options = '') => `<text x="${x}" y="${y}" ${options}>${esc(value)}</text>`;

