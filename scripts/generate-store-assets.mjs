function bubble(x, y, width, height, fill, stroke = 'none', radius = 13) {
  return `<rect x="${x}" y="${y}" width="${width}" height="${height}" rx="${radius}" fill="${fill}" stroke="${stroke}"/>`;
}

function thread(locale, sceneName) {
  const c = locales[locale];
  const scene = c.scenes[sceneName];
  if (sceneName === 'provider') {
    return `${bubble(853, 314, 330, 105, '#f8fafc', '#dbe4f0')}
      ${text(871, 342, scene.localTitle, 'class="bubble-title"')}
      ${scene.localLines.map((line, i) => text(871, 368 + i * 18, line, 'class="bubble-copy"')).join('')}
      ${bubble(853, 434, 330, 113, '#f5f3ff', '#c4b5fd')}
      ${text(871, 462, scene.sendTitle, 'class="bubble-title"')}
      ${scene.sendLines.map((line, i) => text(871, 488 + i * 18, line, 'class="bubble-copy"')).join('')}`;
  }

  const userWidth = sceneName === 'evidence' ? 278 : sceneName === 'confirm' ? 203 : 142;
  const userX = 1183 - userWidth;
  let markup = `${bubble(userX, 314, userWidth, 42, '#4f46e5')} ${text(userX + 14, 340, scene.user, 'class="user-copy"')}`;
  if (sceneName === 'summary') {
    markup += `${bubble(853, 374, 330, 154, '#f8fafc', '#e2e8f0')}${text(871, 404, scene.title, 'class="bubble-title"')}${scene.lines.map((line, i) => `${text(871, 436 + i * 26, '•', 'class="bullet"')}${text(887, 436 + i * 26, line, 'class="bubble-copy"')}`).join('')}`;
  } else if (sceneName === 'evidence') {
    markup += scene.activity.map((item, i) => {
      const widths = locale === 'en' ? [73, 89, 131] : [78, 92, 113];
      const x = 853 + widths.slice(0, i).reduce((a, b) => a + b + 6, 0);
      return `${bubble(x, 372, widths[i], 27, '#f8fafc', '#dbe4ed', 14)}${text(x + widths[i] / 2, 390, item, 'class="activity" text-anchor="middle"')}`;
    }).join('');
    markup += `${bubble(853, 414, 330, 199, '#f8fafc', '#e2e8f0')}${text(871, 444, scene.title, 'class="bubble-title"')}${scene.lines.map((line, i) => text(871, 470 + i * 18, line, 'class="bubble-copy"')).join('')}
      <rect x="871" y="520" width="294" height="71" rx="9" fill="#172033"/>${text(884, 542, '.progress-track::after {', 'class="code"')}${text(896, 560, 'width: 72%;', 'class="code"')}${text(884, 578, '}', 'class="code"')}`;
  } else {
    markup += `${bubble(853, 374, 330, 213, '#fffbeb', '#fbbf24', 14)}${text(870, 405, scene.title, 'class="confirm-title"')}${text(870, 436, scene.body, 'class="confirm-copy"')}
      <rect x="870" y="458" width="${locale === 'en' ? 126 : 113}" height="34" rx="8" fill="#059669"/>${text(locale === 'en' ? 933 : 926.5, 480, scene.approve, 'class="confirm-button" text-anchor="middle"')}
      <rect x="${locale === 'en' ? 1004 : 991}" y="458" width="64" height="34" rx="8" fill="#fff" stroke="#cbd5e1"/>${text(locale === 'en' ? 1036 : 1023, 480, scene.deny, 'class="deny-button" text-anchor="middle"')}
      ${scene.hint.map((line, i) => text(870, 527 + i * 18, line, 'class="hint"')).join('')}`;
  }
  return markup;
}

