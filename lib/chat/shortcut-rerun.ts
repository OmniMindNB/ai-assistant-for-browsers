import type { ResolvedShortcut } from '@/lib/shortcuts';

/**
 * 快捷操作消息的重放配方——「重新生成」按这份配方重跑一遍，而不是原样重发消息文本。
 *
 * 普通输入消息重新生成时，把 content 原样再发一次就行；快捷操作不行：消息上存的是标签
 * （如「📄 总结当前网页」），真正发给模型的 prompt 是 buildShortcutExecution 现场拼出来的
 * 另一段文字。把标签当自由文本重发语义就是错的，这正是重新生成按钮此前对这类回复
 * 点了没反应的原因。
 *
 * 存的是解析后的快捷方式本身（几个短字符串），不是展开后的 prompt：
 * - 页面正文按重新生成那一刻的页面重新预取。正文动辄上万字符，冻进 IndexedDB 既是体积
 *   负担也是隐私负担（历史里本就不留页面正文）；何况「重新总结这个页面」理应总结现在的页面。
 * - 存快捷方式定义本身而不是它的 id：用户事后改了或删了这条快捷方式，重放的仍是当时跑过的
 *   那一版，也不会因为快捷方式不见了就失效。
 */
export interface ShortcutRerun {
  shortcut: ResolvedShortcut;
  /** 划词类快捷方式的原始选区：重新生成时页面上的选区多半已经没了，必须存下来才能重放。 */
  selection?: string;
}
